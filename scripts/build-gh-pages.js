const ROOT = path.resolve(__dirname, '..');
const DEFAULT_REPO = 'sanjeev0304/worktree-ci-prototype';

// In pipeline order.
const ENVS = {
  stage: { label: 'STAGE / DEV', color: '#7b3fe4', path: 'stage', step: 'Feature branch push or deploy: true' },
  qa: { label: 'QA', color: '#b26a00', path: 'qa', step: 'PR -> qa, deploy: qa-v* (git tag)' },
  'pre-prod': { label: 'PRE-PROD', color: '#2f5bea', path: 'pre-prod', step: 'PR merged into qa' },
  prod: { label: 'MAIN / PROD', color: '#1b7f3b', path: 'prod', step: 'PR qa -> main, release: release-v* + merge' },
};
const ALIASES = { dev: 'stage' };

// Demo customers per type, matching CUSTOMER_BY_TYPE in src/server.js.
const DEMO_CUSTOMERS = {
  VIP: { id: 'C001', name: 'Acme Industries', isVip: true },
  STANDARD: { id: 'C002', name: 'Globex Retail', isVip: false },
};

const esc = (s) =>
  String(s ?? '').replace(/[&<>"']/g, (c) => ({ '&': '&amp;', '<': '&lt;', '>': '&gt;', '"': '&quot;', "'": '&#39;' })[c]);

function pagesUrl(repo, subpath = '') {
  const [owner, name] = repo.split('/');
  return `https://${owner}.github.io/${name}/${subpath ? subpath.replace(/^\/|\/$/g, '') + '/' : ''}`;
}

const envName = (env) => ALIASES[env] || env;

/** Folder key for a stage build: the task id, else the branch name made URL-safe. */
function stageKey(task, branch) {
  const id = String(task || '').split(',')[0];
  if (/^[0-9]+$/.test(id)) return id;
  const slug = String(branch || '').toLowerCase().replace(/[^a-z0-9]+/g, '-').replace(/^-+|-+$/g, '').slice(0, 60);
  if (!slug) throw new Error('stage builds need --task <numeric issue id> or --branch <name>');
  return slug;
}

/** Path of an environment folder inside gh-pages, e.g. "stage/23" or "qa". */
function subpathFor(env, task, branch) {
  env = envName(env);
  if (!ENVS[env]) throw new Error(`--env must be one of: ${Object.keys(ENVS).join(', ')}`);
  return env === 'stage' ? `stage/${stageKey(task, branch)}` : ENVS[env].path;
}

/** Links to every task in a "23,24" list. */
const taskLinks = (repo, task) =>
  String(task || '')
    .split(',')
    .filter(Boolean)
    .map((t) => `<a href="https://github.com/${esc(repo)}/issues/${esc(t)}">#${esc(t)}</a>`)
    .join(' ') || 'n/a';

/** Wraps the UI-layer source in a tiny CommonJS loader, with a stub core layer. */
function bundle(dashboardSource) {
  return `/* Generated by scripts/build-gh-pages.js. Do not edit. */
(function () {
  'use strict';
  var sources = {
    './core-engine': function (module) {
      function unavailable() { throw new Error('The core auth/database layer is not shipped to static builds.'); }
      module.exports = { connectDatabase: unavailable, disconnectDatabase: unavailable, isConnected: function () { return false; },
        authenticate: unavailable, requireSession: unavailable, getCustomer: unavailable };
    },
    './invoice-dashboard': function (module, exports, require) {
${dashboardSource}
    },
  };
  var cache = {};
  function load(name) {
    if (!cache[name]) { cache[name] = { exports: {} }; sources[name](cache[name], cache[name].exports, load); }
    return cache[name].exports;
  }
  var dashboard = load('./invoice-dashboard');
  var customers = ${JSON.stringify(DEMO_CUSTOMERS)};
  var $ = function (id) { return document.getElementById(id); };
  var fmt = function (n) { return '\\u20b9' + Number(n).toLocaleString('en-IN', { minimumFractionDigits: 2, maximumFractionDigits: 2 }); };

  function calculate(event) {
    if (event) event.preventDefault();
    var customer = customers[$('customerType').value];
    var amount = Number($('amount').value);
    if (!(amount > 0)) { $('r-customer').textContent = 'Error: amount must be a positive number'; return; }
    var inv = dashboard.calculateInvoice([{ description: 'Enterprise services', quantity: 1, unitPrice: amount }], customer);
    var discountRate = customer.isVip ? dashboard.VIP_DISCOUNT : 0;
    $('r-customer').textContent = customer.name + (customer.isVip ? ' (VIP)' : ' (STANDARD)');
    $('r-subtotal').textContent = fmt(inv.subtotal);
    $('r-discount').textContent = '\\u2212' + fmt(inv.discount) + ' (' + Math.round(discountRate * 100) + '%)';
    $('r-gst').textContent = fmt(inv.gst) + ' (' + Math.round(dashboard.GST_RATE * 100) + '%)';
    $('r-total').textContent = fmt(inv.total);
    var ok = dashboard.GST_RATE === 0.18 && dashboard.VIP_DISCOUNT <= 0.1;
    $('r-rule').textContent = ok ? '\\u2714 Compliant' : '\\u2716 Violated';
    $('r-rule').className = 'status ' + (ok ? 'good' : 'bad');
    document.body.dataset.ready = 'true';
  }
  $('invoice-form').addEventListener('submit', calculate);
  calculate();
})();
`;
}

